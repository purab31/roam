async function seedDatabase() {
  console.log('[Seed] Connecting to MongoDB...');
  await connectDB();

  try {
    const salt = await bcrypt.genSalt(10);
    const defaultPasswordHash = await bcrypt.hash(seedPassword, salt);

    console.log('[Seed] Seeding sample sellers...');
    const createdUsers = [];

    for (const sellerData of sampleSellers) {
      let user = await User.findOne({ email: sellerData.email });
      if (!user) {
        user = await User.create({
          fullName: sellerData.fullName,
          email: sellerData.email,
          mobile: sellerData.mobile,
          passwordHash: defaultPasswordHash,
          capabilities: sellerData.capabilities,
          accountStatus: 'active',
          contactVisibility: sellerData.contactVisibility,
        });
        console.log(`[Seed] Created seller: ${sellerData.fullName} (${sellerData.email})`);
      } else {
        user.fullName = sellerData.fullName;
        user.mobile = sellerData.mobile;
        user.capabilities = sellerData.capabilities;
        user.contactVisibility = sellerData.contactVisibility;
        user.accountStatus = 'active';
        await user.save();
      }
      createdUsers.push(user);
    }

    console.log(`[Seed] Seeding ${vehicleDataset.length} vehicles and marketplace listings...`);
    let createdCount = 0;
    let updatedCount = 0;

    for (let i = 0; i < vehicleDataset.length; i++) {
      const vData = vehicleDataset[i];
      const assignedSeller = createdUsers[i % createdUsers.length];
      const isDealer = assignedSeller.capabilities.includes('dealer');

      const bodyTypeKey = (vData.bodyType || 'suv').toLowerCase();
      const photoKey = `${vData.brand}-${vData.model}`;
      const carPhotoUrl =
        samplePhotoMappings[photoKey] ||
        vData.placeholder ||
        `/uploads/images/placeholders/placeholder-${bodyTypeKey}.svg`;

      // 1. Upsert Vehicle by unique registrationNumber
      let vehicle = await Vehicle.findOne({ registrationNumber: vData.reg });

      // Preserve user-uploaded photos if already present on this vehicle
      const existingUserPhotos = vehicle?.images?.filter(
        img => img.url?.startsWith('/uploads/images/') && !img.url?.includes('placeholder')
      );
      const vehicleImages =
        existingUserPhotos && existingUserPhotos.length > 0
          ? existingUserPhotos
          : [
              {
                url: carPhotoUrl,
                isCover: true,
                order: 0,
                caption: `${vData.brand} ${vData.model} - Exterior Profile`,
              },
            ];

      const vehiclePayload = {
        brand: vData.brand,
        model: vData.model,
        variant: vData.variant,
        bodyType: vData.bodyType,
        manufacturingYear: vData.year,
        registrationYear: vData.year,
        registrationNumber: vData.reg,
        fuelType: vData.fuel,
        transmission: vData.trans,
        kmDriven: vData.km,
        previousOwners: vData.owners,
        condition: vData.cond,
        colour: vData.colour,
        seatingCapacity: vData.bodyType === 'Minivan' ? 7 : 5,
        location: {
          country: 'India',
          state: vData.state,
          city: vData.city,
          area: vData.area,
          pincode: vData.pincode,
          pickupLocation: `${vData.area}, ${vData.city}`,
        },
        features: vData.features,
        knownDefects: 'None. Certified pre-owned inspection completed.',
        serviceHistory: 'Full authorized service records available.',
        accidentHistory: 'Clean title. No structural or major accidents reported.',
        insuranceInfo: 'Comprehensive insurance valid for current year.',
        pollutionCertInfo: 'Valid PUC certified.',
        images: vehicleImages,
        ownerRef: {
          type: isDealer ? 'dealer' : 'user',
          id: assignedSeller._id,
        },
      };

      if (!vehicle) {
        vehicle = await Vehicle.create(vehiclePayload);
      } else {
        Object.assign(vehicle, vehiclePayload);
        await vehicle.save();
      }

      // 2. Upsert Listing for this vehicle
      let listing = await Listing.findOne({ vehicleRef: vehicle._id });

      const saleAskingPaise = vData.priceRupees ? vData.priceRupees * 100 : 0;
      const minAcceptableOfferPaise = vData.priceRupees
        ? Math.round(vData.priceRupees * 0.92) * 100
        : 0;
      const rentalDailyPaise = vData.rentDailyRupees ? vData.rentDailyRupees * 100 : 0;

      const saleSubdoc = {
        enabled: vData.purpose === 'sale' || vData.purpose === 'both',
        status: vData.purpose === 'rent' ? 'inactive' : 'active',
        askingPrice: saleAskingPaise,
        negotiable: true,
        minAcceptableOffer: minAcceptableOfferPaise,
        description: `Immaculate condition ${vData.brand} ${vData.model} ${vData.variant} (${vData.year}). Thoroughly inspected and verified. Includes ${vData.features.slice(0, 3).join(', ')}.`,
        conditions: 'Transfer of ownership and payment settled directly between buyer and seller as per Roam guidelines.',
      };

      const rentalSubdoc = {
        dailyPrice: rentalDailyPaise,
        weeklyPrice: rentalDailyPaise ? rentalDailyPaise * 6 : 0,
        securityDeposit: rentalDailyPaise ? rentalDailyPaise * 4 : 0,
        minDays: 1,
        maxDays: 30,
        pickupLocation: `${vData.area}, ${vData.city}`,
        returnLocation: `${vData.area}, ${vData.city}`,
        driverIncluded: false,
        mileageLimit: '250 km / day',
        fuelPolicy: 'Same to same',
        cancellationPolicy: 'Free cancellation up to 24 hours before pickup',
        conditions: 'Valid driving licence and government ID required upon pickup.',
        status: vData.purpose === 'sale' ? 'inactive' : 'active',
      };

      if (!listing) {
        listing = await Listing.create({
          vehicleRef: vehicle._id,
          ownerRef: {
            type: isDealer ? 'dealer' : 'user',
            id: assignedSeller._id,
          },
          purpose: vData.purpose,
          moderationStatus: 'approved',
          sale: saleSubdoc,
          rental: rentalSubdoc,
          statusHistory: [
            {
              fromStatus: 'draft',
              toStatus: 'approved',
              statusType: 'moderation',
              changedAt: new Date(),
              reason: 'Initial development marketplace seed',
            },
          ],
        });
        createdCount++;
      } else {
        listing.purpose = vData.purpose;
        listing.moderationStatus = 'approved';
        listing.sale = saleSubdoc;
        listing.rental = rentalSubdoc;
        await listing.save();
        updatedCount++;
      }
    }

    console.log(`[Seed Complete] Successfully processed ${vehicleDataset.length} listings!`);
    console.log(`Created: ${createdCount} listings, Updated: ${updatedCount} listings.`);
    console.log(`Log in as any seed seller with password: ${seedPassword}`);
  } catch (err) {
    console.error('[Seed Error] Failed to seed marketplace:', err);
  } finally {
    await disconnectDB();
  }
}

if (require.main === module) {
  seedDatabase();
}

module.exports = seedDatabase;